//! Эффект: программа, заполняющая Фреймбуфер на каждый Кадр.
//!
//! Контракт — как в WLED: за вызов Эффект обязан заполнить Кадр целиком.
//! Состояние инкапсулировано в реализации (в отличие от глобального
//! контекста WLED), время приходит снаружи, поэтому математика Эффектов
//! детерминированна и проверяется тестами на хосте.

use crate::frame::Frame;

/// Эффект — программа Кадра; Реестр Прошивки листает реализации по кругу.
///
/// Реализации — Аддоны (крейты `effects/effect-*`); Прошивка создаёт их
/// фабриками в момент включения и держит ровно один экземпляр Текущего
/// эффекта.
pub trait Effect {
    /// Заполнить Кадр целиком на момент `elapsed_ms` — миллисекунды с момента
    /// запуска этого экземпляра Эффекта: машина Гирлянды ведёт для каждого
    /// экземпляра свою шкалу, так что вывод Эффекта всегда начинается с нуля.
    fn render(&mut self, frame: &mut Frame<'_>, elapsed_ms: u32);
}
